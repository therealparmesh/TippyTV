package com.parmesh.livetv;

import android.content.Context;
import android.content.SharedPreferences;
import android.security.keystore.KeyGenParameterSpec;
import android.security.keystore.KeyProperties;
import android.util.Base64;

import okhttp3.HttpUrl;

import org.json.JSONArray;

import java.nio.charset.StandardCharsets;
import java.security.KeyStore;
import java.util.List;
import java.util.UUID;

import javax.crypto.Cipher;
import javax.crypto.KeyGenerator;
import javax.crypto.SecretKey;
import javax.crypto.spec.GCMParameterSpec;

final class SessionStore {
    private static final String KEY = "jellyfin-live-session";
    private final SharedPreferences prefs;

    SessionStore(Context context) {
        prefs = context.getSharedPreferences("session", Context.MODE_PRIVATE);
    }

    String device() {
        String device = prefs.getString("device", null);
        if (device == null) {
            device = UUID.randomUUID().toString();
            prefs.edit().putString("device", device).apply();
        }
        return device;
    }

    String address() {
        return prefs.getString("server", "");
    }

    Jellyfin.Session read() {
        String active = prefs.getString("active", null);
        if (active != null) {
            try {
                String[] blob = prefs.getString("profile." + active, "").split(":", 2);
                JSONArray a = new JSONArray(decrypt(blob[0], blob[1]));
                String playlist = a.getString(4), guide = a.getString(5);
                return new Jellyfin.Session(
                        a.getString(0),
                        a.getString(1),
                        a.getString(2),
                        a.length() > 6 ? a.getString(6) : device(),
                        a.getString(3),
                        playlist,
                        guide,
                        a.length() > 7 ? a.getBoolean(7) : legacyXtream(playlist, guide));
            } catch (Exception unreadable) {
                return null;
            }
        }
        String token = prefs.getString("token", null);
        if (token == null) return null;
        try {
            Jellyfin.Session legacy =
                    new Jellyfin.Session(
                            address(),
                            decrypt(prefs.getString("iv", ""), token),
                            prefs.getString("user", ""),
                            device());
            save(legacy);
            return legacy;
        } catch (Exception unreadable) {
            return null;
        }
    }

    // Earlier releases stored only URLs. Match the exact pair generated by Xtream setup.
    static boolean legacyXtream(String playlist, String guide) {
        HttpUrl url = HttpUrl.parse(playlist);
        if (url == null || !"get.php".equals(url.pathSegments().get(url.pathSize() - 1)))
            return false;
        String user = url.queryParameter("username"), password = url.queryParameter("password");
        if (user == null || password == null) return false;
        Jellyfin.Session generated = Jellyfin.Session.xtream("", url.resolve("."), user, password);
        return playlist.equals(generated.playlist()) && guide.equals(generated.guide());
    }

    private String decrypt(String iv, String data) throws Exception {
        Cipher cipher = Cipher.getInstance("AES/GCM/NoPadding");
        cipher.init(
                Cipher.DECRYPT_MODE,
                key(),
                new GCMParameterSpec(128, Base64.decode(iv, Base64.NO_WRAP)));
        return new String(
                cipher.doFinal(Base64.decode(data, Base64.NO_WRAP)), StandardCharsets.UTF_8);
    }

    List<String> ids() {
        return prefs.getAll().keySet().stream()
                .filter(k -> k.startsWith("profile."))
                .map(k -> k.substring(8))
                .sorted(java.util.Comparator.comparing(this::label))
                .collect(java.util.stream.Collectors.toList());
    }

    String label(String id) {
        return prefs.getString("label." + id, "Profile");
    }

    String activeId() {
        return prefs.getString("active", "");
    }

    void activate(String id) {
        prefs.edit().putString("active", id).apply();
    }

    private static String profileId(Jellyfin.Session session) {
        return UUID.nameUUIDFromBytes(
                        (session.server() + "\n" + session.user()).getBytes(StandardCharsets.UTF_8))
                .toString();
    }

    synchronized void save(Jellyfin.Session session) throws Exception {
        String id = profileId(session);
        JSONArray a =
                new JSONArray()
                        .put(session.server())
                        .put(session.token())
                        .put(session.user())
                        .put(session.name())
                        .put(session.playlist())
                        .put(session.guide())
                        .put(session.device())
                        .put(session.xtream());
        Cipher cipher = Cipher.getInstance("AES/GCM/NoPadding");
        cipher.init(Cipher.ENCRYPT_MODE, key());
        String blob =
                Base64.encodeToString(cipher.getIV(), Base64.NO_WRAP)
                        + ":"
                        + Base64.encodeToString(
                                cipher.doFinal(a.toString().getBytes(StandardCharsets.UTF_8)),
                                Base64.NO_WRAP);
        SharedPreferences.Editor edit =
                prefs.edit()
                        .putString("profile." + id, blob)
                        .putString("label." + id, session.label())
                        .putString("active", id)
                        .remove("token")
                        .remove("user")
                        .remove("iv");
        if (!session.direct()) edit.putString("server", session.server());
        if (!edit.commit()) throw new java.io.IOException("Could not save profile.");
    }

    synchronized void clear(Jellyfin.Session session) {
        String id = profileId(session);
        SharedPreferences.Editor edit = prefs.edit().remove("profile." + id).remove("label." + id);
        if (id.equals(activeId())) edit.remove("active");
        edit.apply();
    }

    private SecretKey key() throws Exception {
        KeyStore store = KeyStore.getInstance("AndroidKeyStore");
        store.load(null);
        if (store.getKey(KEY, null) instanceof SecretKey key) return key;
        KeyGenerator generator =
                KeyGenerator.getInstance(KeyProperties.KEY_ALGORITHM_AES, "AndroidKeyStore");
        generator.init(
                new KeyGenParameterSpec.Builder(
                                KEY, KeyProperties.PURPOSE_ENCRYPT | KeyProperties.PURPOSE_DECRYPT)
                        .setBlockModes(KeyProperties.BLOCK_MODE_GCM)
                        .setEncryptionPaddings(KeyProperties.ENCRYPTION_PADDING_NONE)
                        .build());
        return generator.generateKey();
    }
}
